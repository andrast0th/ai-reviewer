import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { HttpError, UsageError } from "../src/errors.ts";
import { GitlabClient, GitlabShapeError, parseMergeRequest } from "../src/gitlab.ts";
import { silentLogger } from "../src/log.ts";
import { parseMrRef } from "../src/mrUrl.ts";
import { changedFromMrDiffs } from "../src/review/sources.ts";
import { fakeFetch, fixtureJson } from "./helpers.ts";

const GL = "https://gitlab.test";
const API = `${GL}/api/v4`;
const cfg = { url: GL, workspace: "/tmp/x", sshHost: "gitlab.test" };

describe("parseMrRef", () => {
  it("parses MR URLs, including nested groups and trailing tabs", () => {
    for (const url of [
      `${GL}/acme/payments/bank/-/merge_requests/7`,
      `${GL}/acme/payments/bank/-/merge_requests/7/diffs`,
      `${GL}/acme/payments/bank/-/merge_requests/7#note_1`,
      `${GL}/acme/payments/bank/merge_requests/7`,
    ]) {
      assert.deepEqual(parseMrRef([url], GL), { projectPath: "acme/payments/bank", iid: 7 }, url);
    }
  });

  it("handles a GitLab hosted under a path prefix", () => {
    assert.deepEqual(
      parseMrRef(["https://corp.test/gitlab/a/b/-/merge_requests/3"], "https://corp.test/gitlab"),
      {
        projectPath: "a/b",
        iid: 3,
      },
    );
    assert.throws(
      () => parseMrRef(["https://corp.test/a/b/-/merge_requests/3"], "https://corp.test/gitlab"),
      UsageError,
    );
  });

  it("accepts project + iid and project!iid", () => {
    assert.deepEqual(parseMrRef(["acme/bank", "12"], GL), { projectPath: "acme/bank", iid: 12 });
    assert.deepEqual(parseMrRef(["acme/bank!12"], GL), { projectPath: "acme/bank", iid: 12 });
  });

  it("refuses other hosts and malformed input", () => {
    const bad: string[][] = [
      ["https://evil.test/acme/bank/-/merge_requests/1"],
      [`${GL}/acme/bank/-/issues/1`],
      [`${GL}/acme/bank/-/merge_requests/abc`],
      ["acme/bank", "0"],
      ["bank", "1"],
      ["../etc", "1"],
      ["acme/../bank", "1"],
      ["a", "b", "c"],
    ];
    for (const args of bad) assert.throws(() => parseMrRef(args, GL), UsageError, args.join(" "));
  });
});

describe("GitlabClient", () => {
  function client(routes: Parameters<typeof fakeFetch>[0]) {
    const f = fakeFetch(routes);
    return { f, c: new GitlabClient({ cfg, token: "glpat-t", log: silentLogger(), fetch: f }) };
  }

  it("looks up projects by URL-encoded path", async () => {
    const { f, c } = client({
      [`GET ${API}/projects/acme%2Fpayments%2Fbank`]: { json: fixtureJson("gitlab/project.json") },
    });
    const p = await c.project("acme/payments/bank");
    assert.deepEqual(p, {
      id: 321,
      pathWithNamespace: "acme/payments/bank",
      sshUrl: "git@gitlab.test:acme/payments/bank.git",
      webUrl: "https://gitlab.test/acme/payments/bank",
    });
    assert.equal(f.calls[0]?.headers["private-token"], "glpat-t");
  });

  it("explains a 404 project", async () => {
    const { c } = client({});
    await assert.rejects(
      c.project("acme/nope"),
      (e: unknown) =>
        e instanceof HttpError && /not found, or the token cannot see it/.test(e.message),
    );
  });

  it("parses merge requests and requires diff_refs", async () => {
    const mr = parseMergeRequest(fixtureJson("gitlab/mr.json"));
    assert.equal(mr.iid, 7);
    assert.equal(mr.targetBranch, "main");
    assert.equal(mr.author, "test.user");
    assert.equal(mr.diffRefs.headSha, "2".repeat(40));
    const noRefs = { ...(fixtureJson("gitlab/mr.json") as object), diff_refs: null };
    assert.throws(() => parseMergeRequest(noRefs), GitlabShapeError);
  });

  it("follows diff pagination via x-next-page", async () => {
    const { f, c } = client({
      [`GET ${API}/projects/321/merge_requests/7/diffs`]: [
        { json: fixtureJson("gitlab/mr-diffs-page1.json"), headers: { "x-next-page": "2" } },
        { json: fixtureJson("gitlab/mr-diffs-page2.json"), headers: { "x-next-page": "" } },
      ],
    });
    const entries = await c.mergeRequestDiffs(321, 7);
    assert.equal(entries.length, 4);
    assert.deepEqual(
      f.calls.map((x) => x.url.searchParams.get("page")),
      ["1", "2"],
    );
    const { changed, presetSkips } = changedFromMrDiffs(entries);
    assert.deepEqual(
      changed.map((x) => [x.status, x.oldPath, x.newPath]),
      [
        ["modified", "src/A.java", "src/A.java"],
        ["renamed", "old/B.kt", "new/B.kt"],
        ["added", "gen/Api.ts", "gen/Api.ts"],
        ["deleted", "gone.js", "gone.js"],
      ],
    );
    assert.deepEqual([...presetSkips], [["gen/Api.ts", "marked as generated by GitLab"]]);
  });
});
