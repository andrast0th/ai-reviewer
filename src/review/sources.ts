import { PathFilter } from "../context/filters.ts";
import { parseFileDiff } from "../diff.ts";
import type { ChangedFile, GitRepo } from "../git.ts";
import type { MrDiffEntry } from "../gitlab.ts";
import type { ReviewFile, SkippedFile } from "./engine.ts";

/** Files above this size are not reviewed at all. */
export const MAX_FILE_BYTES = 1024 * 1024;

export interface CollectedFiles {
  files: ReviewFile[];
  skipped: SkippedFile[];
}

/**
 * Turn a list of changed files into review inputs: the diff with wide context and the full
 * content at `head`, both read from the local repository. Files that can't or shouldn't be
 * reviewed are returned in `skipped` with a reason. `presetSkips` lets a source veto files
 * up front (e.g. GitLab's generated-file flag).
 */
export async function collectFiles(
  repo: GitRepo,
  base: string,
  head: string,
  changed: readonly ChangedFile[],
  exclude: readonly string[],
  presetSkips: ReadonlyMap<string, string> = new Map(),
): Promise<CollectedFiles> {
  const filter = new PathFilter(exclude);
  const files: ReviewFile[] = [];
  const skipped: SkippedFile[] = [];
  for (const cf of changed) {
    const path = cf.newPath;
    const preset = presetSkips.get(path);
    if (preset) {
      skipped.push({ path, reason: preset });
      continue;
    }
    if (cf.status === "deleted") {
      skipped.push({ path, reason: "deleted" });
      continue;
    }
    if (filter.excludes(path)) {
      skipped.push({ path, reason: "excluded by review.exclude" });
      continue;
    }
    const size = await repo.fileSize(head, path);
    if (size > MAX_FILE_BYTES) {
      skipped.push({ path, reason: `too large (${Math.round(size / 1024)} KiB)` });
      continue;
    }
    const diff = parseFileDiff(await repo.fileDiff(base, head, cf));
    if (diff.binary) {
      skipped.push({ path, reason: "binary" });
      continue;
    }
    if (diff.hunks.length === 0) {
      skipped.push({
        path,
        reason: cf.status === "renamed" ? "renamed without changes" : "no content change",
      });
      continue;
    }
    files.push({ path, diff, content: await repo.showFile(head, path) });
  }
  return { files, skipped };
}

// ------------------------------------------------------------ local branch

export interface LocalChange extends CollectedFiles {
  repoDir: string;
  baseRef: string;
  /** merge-base of base and HEAD: what the branch is compared against. */
  baseSha: string;
  headSha: string;
  branch: string | undefined;
  dirty: boolean;
}

/**
 * Collect the committed changes of HEAD relative to its merge-base with `baseRef`, like
 * `git diff base...HEAD`. File contents come from the HEAD commit, not the working tree.
 */
export async function collectLocalChange(
  repo: GitRepo,
  baseRef: string,
  exclude: readonly string[],
): Promise<LocalChange> {
  await repo.assertRepo();
  const headSha = await repo.resolveCommit("HEAD");
  const baseTip = await repo.resolveCommit(baseRef);
  const baseSha = await repo.mergeBase(baseTip, headSha);
  const collected = await collectFiles(
    repo,
    baseSha,
    headSha,
    await repo.changedFiles(baseSha, headSha),
    exclude,
  );
  return {
    repoDir: repo.dir,
    baseRef,
    baseSha,
    headSha,
    branch: await repo.currentBranch(),
    dirty: await repo.isDirty(),
    ...collected,
  };
}

// ------------------------------------------------------------ GitLab merge request

/** GitLab's list of changed files, in our shape, plus files GitLab marks as generated. */
export function changedFromMrDiffs(entries: readonly MrDiffEntry[]): {
  changed: ChangedFile[];
  presetSkips: Map<string, string>;
} {
  const changed: ChangedFile[] = entries.map((e) => ({
    status: e.deletedFile
      ? "deleted"
      : e.newFile
        ? "added"
        : e.renamedFile
          ? "renamed"
          : "modified",
    oldPath: e.oldPath || e.newPath,
    newPath: e.newPath || e.oldPath,
  }));
  const presetSkips = new Map<string, string>();
  for (const e of entries) {
    if (e.generatedFile && !e.deletedFile)
      presetSkips.set(e.newPath, "marked as generated by GitLab");
  }
  return { changed, presetSkips };
}
